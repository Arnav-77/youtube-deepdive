"""Write evaluation/REPORT_DATA.md: every table and number the final report uses.

    python evaluation/report_data.py

Reads result files only (no database, no network) and copies each number with
the file it is read from and the command that produced that file, so a reader
can check any number in the report. Rerun after the result files change (for
example after Arnav's production export) and commit the new REPORT_DATA.md.

Labels used below:
  HUMAN  labelled by Arnav (golden_set.yaml, grounding_labels.yaml)
  AI     written or labelled by Claude Code (golden_set_agent.yaml,
         grounding_labels_agent.yaml); never mixed into HUMAN numbers
  NOTES  a fact from Arnav's notes in report_src/finish_plan.md that the
         repository alone cannot show
"""

import json
