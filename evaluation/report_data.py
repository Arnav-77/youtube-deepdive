def load(name):
    p = RESULTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def pct(a, b):
    return f"{100 * a / b:.1f}% ({a}/{b})" if b else "n/a (0/0)"


def f3(v):
    return "n/a" if v is None else f"{v:.3f}"


def retrieval_table(rows, labels, set_):
    out = ["| Questions | Method | Recall@5 | MRR | Recall@1 | median abs offset | late |",
           "|---|---|---|---|---|---|---|"]
    for r in rows:
        if r["labels"] != labels or r["set"] != set_ or not r["n"]:
            continue
        off = "n/a" if r["abs_offset_median"] is None else f"{r['abs_offset_median']:.0f} s"
        out.append(f"| {r['questions']} | {r['method']} | {f3(r['recall'])} ({r['hits']}/{r['n']}) | "
                   f"{f3(r['mrr'])} | {r['rank1']}/{r['n']} | {off} | {r['late']}/{r['hits']} |")
    return out


def grounding_lines(key, g):
    if not g:
        return [f"- {key}: not in summary.json"]
    rt = g["refusal"]
    lines = [f"- **{g['title']}** (key `{key}`)",
             f"  - answers {g['answers']}, refused {g['refused']}, answered {g['answered']}, segments {g['segments']}",
             f"  - grounding rate {pct(g['supported'], g['segments'])}; partly {pct(g['partly'], g['segments'])}; "
             f"unsupported {pct(g['unsupported'], g['segments'])}",
             f"  - answer-level (every segment supported) {pct(g['every_segment_supported'], g['answered'])}",
             f"  - refusals: correct {rt['correct_refusal']}, missed {rt['missed_refusal']}, false {rt['false_refusal']} "
             f"(retrieval {rt['false_refusal_retrieval']}, generation {rt['false_refusal_generation']}), "
             f"answered with gold {rt['answered_with_gold']}",
             f"  - wrong-link notes {g['wrong_link_notes']}; answers citing unsent excerpts {g['answers_citing_unsent']}"]
    for m, s in (g.get("by_model") or {}).items():
        lines.append(f"  - model {m}: answer-level {pct(s['every_segment_supported'], s['answered'])}, "
                     f"segments {pct(s['supported'], s['segments'])}")
    return lines


